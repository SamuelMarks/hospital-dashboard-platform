/**
 * @fileoverview Unit tests for the AST TSDoc coverage verifier (`scripts/verify_docs.ts`).
 */

import { describe, it, expect, vi } from 'vitest';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import * as ts from 'typescript';
import {
  isPlaceholderDoc,
  flattenJsDocComment,
  verifySourceFileText,
  verifyFrontendDocs,
} from '../../scripts/verify_docs';

describe('scripts/verify_docs.ts', () => {
  it('detects empty and banned placeholder JSDoc strings', () => {
    expect(isPlaceholderDoc('')).toBe(true);
    expect(isPlaceholderDoc('   ')).toBe(true);
    expect(isPlaceholderDoc('@docs')).toBe(true);
    expect(isPlaceholderDoc('Autogenerated doc')).toBe(true);
    expect(isPlaceholderDoc('store property.')).toBe(true);
    expect(isPlaceholderDoc('Chat store.')).toBe(true);
    expect(isPlaceholderDoc('Store.')).toBe(true);
    expect(isPlaceholderDoc('Creates a new ChatStore.')).toBe(true);
    expect(isPlaceholderDoc('Ng On Init.')).toBe(true);
    expect(isPlaceholderDoc('Initialize component.')).toBe(true);
    expect(isPlaceholderDoc('Centralized reactive state store for hospital dashboards.')).toBe(
      false,
    );
  });

  it('flattens string, undefined, and NodeArray JSDoc comments', () => {
    expect(flattenJsDocComment(undefined)).toBe('');
    expect(flattenJsDocComment('  Hello world  ')).toBe('Hello world');
    const mockArray = [
      { text: 'Part 1 ' },
      { text: 'Part 2' },
    ] as unknown as ts.NodeArray<ts.JSDocComment>;
    expect(flattenJsDocComment(mockArray)).toBe('Part 1 Part 2');
  });

  it('verifies AST declarations and reports missing or placeholder docs', () => {
    const invalidSource = `
      export class UndocClass {
        prop = 1;
        constructor(a: string) {}
        get val(): number { return 1; }
        set val(v: number) {}
        /** Store. */
        badMethod(x: number, y: number): void {}
      }
      export interface UndocIntf {
        field: string;
        act(): void;
      }
      export type UndocType = string;
      export enum UndocEnum {
        A = 'a',
      }
      /**
       * Valid function doc.
       * @param a - store property.
       */
      export function partialFn(a: string, b: number): void {}
    `;
    const errors = verifySourceFileText(invalidSource, 'test.ts');
    expect(errors.some((e) => e.includes('Missing @fileoverview'))).toBe(true);
    expect(errors.some((e) => e.includes('class UndocClass'))).toBe(true);
    expect(errors.some((e) => e.includes('property UndocClass.prop'))).toBe(true);
    expect(errors.some((e) => e.includes('getter UndocClass.val'))).toBe(true);
    expect(errors.some((e) => e.includes('setter UndocClass.val'))).toBe(true);
    expect(errors.some((e) => e.includes('method UndocClass.badMethod'))).toBe(true);
    expect(errors.some((e) => e.includes('interface UndocIntf'))).toBe(true);
    expect(errors.some((e) => e.includes('interface property UndocIntf.field'))).toBe(true);
    expect(errors.some((e) => e.includes('interface method UndocIntf.act'))).toBe(true);
    expect(errors.some((e) => e.includes('type UndocType'))).toBe(true);
    expect(errors.some((e) => e.includes('enum UndocEnum'))).toBe(true);
    expect(errors.some((e) => e.includes('enum member UndocEnum.A'))).toBe(true);
    expect(errors.some((e) => e.includes('Placeholder or empty @param a'))).toBe(true);
    expect(errors.some((e) => e.includes('Missing @param b'))).toBe(true);
  });

  it('passes valid source files and reports failures via verifyFrontendDocs', () => {
    const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'verify-docs-'));
    const validFile = path.join(tmpDir, 'valid.ts');
    fs.writeFileSync(
      validFile,
      `/** @fileoverview Valid module. */
/** Valid constant type. */
export type ValidId = string;
`,
      'utf8',
    );
    expect(verifyFrontendDocs(tmpDir)).toBe(0);

    const invalidFile = path.join(tmpDir, 'invalid.ts');
    fs.writeFileSync(
      invalidFile,
      `/** @doc */
export type BadId = string;
`,
      'utf8',
    );
    const errSpy = vi.spyOn(console, 'error').mockImplementation(() => {});
    expect(verifyFrontendDocs(tmpDir)).toBe(1);
    errSpy.mockRestore();
    fs.rmSync(tmpDir, { recursive: true, force: true });
  });
});
