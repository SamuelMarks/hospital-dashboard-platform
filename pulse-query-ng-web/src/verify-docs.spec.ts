/**
 * @fileoverview Unit tests for the AST TSDoc coverage verifier (`scripts/verify_docs.ts`).
 */

import { describe, it, expect, vi } from 'vitest';
import * as fs from 'fs';
import * as os from 'os';
import * as path from 'path';
import * as ts from 'typescript';
import {
  isPlaceholderDoc,
  flattenJsDocComment,
  verifyNodeDoc,
  verifyParameterDocs,
  verifySourceFileText,
  verifyFrontendDocs,
  runCliIfMain,
} from '../../scripts/verify_docs';

describe('scripts/verify_docs.ts', () => {
  it('detects empty and banned placeholder JSDoc strings', () => {
    expect(isPlaceholderDoc('')).toBe(true);
    expect(isPlaceholderDoc('   ')).toBe(true);
    expect(isPlaceholderDoc('@docs')).toBe(true);
    expect(isPlaceholderDoc('Autogenerated doc')).toBe(true);
    expect(isPlaceholderDoc('store property.')).toBe(true);
    expect(isPlaceholderDoc('Chat store.')).toBe(true);
    expect(isPlaceholderDoc('Store.')).toBe(true);
    expect(isPlaceholderDoc('Constructor.')).toBe(true);
    expect(isPlaceholderDoc('Creates a new ChatStore.')).toBe(true);
    expect(isPlaceholderDoc('Ng On Init.')).toBe(true);
    expect(isPlaceholderDoc('Initialize component.')).toBe(true);
    expect(isPlaceholderDoc('Centralized reactive state store for hospital dashboards.')).toBe(
      false,
    );
  });

  it('flattens string, undefined, and NodeArray JSDoc comments', () => {
    expect(flattenJsDocComment(undefined)).toBe('');
    expect(flattenJsDocComment('  Hello world  ')).toBe('Hello world');
    const nodeArray = ts.factory.createNodeArray([
      ts.factory.createJSDocText('Part 1 '),
      ts.factory.createJSDocText('Part 2'),
    ]);
    expect(flattenJsDocComment(nodeArray)).toBe('Part 1 Part 2');
  });

  it('verifies AST declarations and reports missing or placeholder docs across all syntax kinds', () => {
    const invalidSource = `
      export class UndocClass {
        ;
        prop = 1;
        constructor(a: string) {}
        get val(): number { return 1; }
        set val(v: number) {}
        /** Store. */
        badMethod(x: number, y: number): void {}
        /**
         * Store.
         * @param x - Valid param description.
         */
        taggedPlaceholderSummary(x: number): void {}
        /**
         * Valid summary description.
         * @returns Autogenerated doc
         */
        taggedPlaceholderBody(): number { return 1; }
      }
      export default class {}
      export interface UndocIntf {
        [key: string]: unknown;
        field: string;
        act(): void;
      }
      export type UndocType = string;
      export enum UndocEnum {
        A = 'a',
      }
      /**
       * Valid function doc.
       * @param a - store property.
       * @param c -
       * @returns Nothing.
       */
      export function partialFn(a: string, b: number, c: boolean): void {}
    `;
    const errors = verifySourceFileText(invalidSource, 'test.ts');
    expect(errors.some((e) => e.includes('Missing @fileoverview'))).toBe(true);
    expect(errors.some((e) => e.includes('class UndocClass'))).toBe(true);
    expect(errors.some((e) => e.includes('class <anonymous class>'))).toBe(true);
    expect(errors.some((e) => e.includes('property UndocClass.prop'))).toBe(true);
    expect(errors.some((e) => e.includes('getter UndocClass.val'))).toBe(true);
    expect(errors.some((e) => e.includes('setter UndocClass.val'))).toBe(true);
    expect(errors.some((e) => e.includes('method UndocClass.badMethod'))).toBe(true);
    expect(errors.some((e) => e.includes('method UndocClass.taggedPlaceholderSummary'))).toBe(true);
    expect(errors.some((e) => e.includes('method UndocClass.taggedPlaceholderBody'))).toBe(true);
    expect(errors.some((e) => e.includes('interface UndocIntf'))).toBe(true);
    expect(errors.some((e) => e.includes('interface property UndocIntf.field'))).toBe(true);
    expect(errors.some((e) => e.includes('interface method UndocIntf.act'))).toBe(true);
    expect(errors.some((e) => e.includes('type UndocType'))).toBe(true);
    expect(errors.some((e) => e.includes('enum UndocEnum'))).toBe(true);
    expect(errors.some((e) => e.includes('enum member UndocEnum.A'))).toBe(true);
    expect(errors.some((e) => e.includes('Placeholder or empty @param a'))).toBe(true);
    expect(errors.some((e) => e.includes('Missing @param b'))).toBe(true);
    expect(errors.some((e) => e.includes('Placeholder or empty @param c'))).toBe(true);

    // Anonymous function declaration
    const anonFnErrors = verifySourceFileText(
      `/** @fileoverview Anon function test. */
const sentinel = 1;
export default function () {}
`,
      'anon-fn.ts',
    );
    expect(anonFnErrors.some((e) => e.includes('function <anonymous function>'))).toBe(true);

    // Banned @docs and Autogenerated doc file-level comments
    const bannedDocErrors1 = verifySourceFileText(
      `/** @fileoverview Header. */
/** @docs */
export type T1 = string;
`,
      'banned1.ts',
    );
    expect(
      bannedDocErrors1.some((e) =>
        e.includes('File contains banned placeholder doc comment (@docs / doc)'),
      ),
    ).toBe(true);

    const bannedDocErrors2 = verifySourceFileText(
      `/** @fileoverview Header. */
/** Autogenerated doc */
export type T2 = string;
`,
      'banned2.ts',
    );
    expect(
      bannedDocErrors2.some((e) =>
        e.includes('File contains banned placeholder doc comment (@docs / doc)'),
      ),
    ).toBe(true);

    // Forbidden AST constructs (any, as unknown as, standalone: true, OnPush)
    const forbiddenTypesSource = `
      /** @fileoverview Test forbidden types. */
      import { SIGNAL } from '@angular/core/primitives/signals';
      /** Bad type alias using any. */
      export type BadAny = any;
      /** Cast value x. */
      export const x = (1 as unknown as string);
      /** Cast value y. */
      export const y = (1 as number);
      /** Component metadata fixture. */
      export const compMeta = {
        standalone: true,
        changeDetection: ChangeDetectionStrategy.OnPush,
        otherProp: 123,
      };
      export const undocExportedVar = 42;
    `;
    const typeErrors = verifySourceFileText(forbiddenTypesSource, 'forbidden.ts');
    expect(typeErrors.some((e) => e.includes('@angular/core/primitives/signals'))).toBe(true);
    expect(typeErrors.some((e) => e.includes("Forbidden 'any' type annotation"))).toBe(true);
    expect(
      typeErrors.some((e) => e.includes("Forbidden 'as unknown as' double type assertion")),
    ).toBe(true);
    expect(typeErrors.some((e) => e.includes("Forbidden 'standalone: true'"))).toBe(true);
    expect(
      typeErrors.some((e) =>
        e.includes("Forbidden 'changeDetection: ChangeDetectionStrategy.OnPush'"),
      ),
    ).toBe(true);
    expect(typeErrors.some((e) => e.includes('variable undocExportedVar'))).toBe(true);

    // Direct verifyNodeDoc and verifyParameterDocs edge cases
    const emptySf = ts.createSourceFile('empty.ts', 'const a = 1;', ts.ScriptTarget.Latest, true);
    const firstStmt = emptySf.statements[0] as ts.Statement;
    const directErrors: string[] = [];
    verifyNodeDoc(emptySf, firstStmt, 'stmt', 'empty.ts', directErrors);
    expect(directErrors).toHaveLength(1);
    verifyParameterDocs(emptySf, firstStmt, [], 'stmt', 'empty.ts', directErrors);
    expect(directErrors).toHaveLength(1);
  });

  it('collects files recursively, skips excluded directories, and runs verifyFrontendDocs & runCliIfMain', () => {
    const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'verify-docs-'));
    fs.mkdirSync(path.join(tmpDir, 'api-client'));
    fs.writeFileSync(path.join(tmpDir, 'api-client', 'ignored.ts'), 'export type X = any;', 'utf8');
    const subDir = path.join(tmpDir, 'feature');
    fs.mkdirSync(subDir);
    fs.writeFileSync(path.join(subDir, 'feature.spec.ts'), 'export type Spec = any;', 'utf8');
    fs.writeFileSync(path.join(subDir, 'feature.d.ts'), 'export type Decl = any;', 'utf8');
    fs.writeFileSync(path.join(subDir, 'test-setup.ts'), 'export type Setup = any;', 'utf8');
    fs.writeFileSync(
      path.join(subDir, 'vitest-setup-entry.ts'),
      'export type Entry = any;',
      'utf8',
    );
    fs.writeFileSync(path.join(subDir, 'README.md'), '# Readme', 'utf8');

    const validFile = path.join(subDir, 'valid.ts');
    fs.writeFileSync(
      validFile,
      `/** @fileoverview Valid module. */
/**
 * Valid function.
 * @param name - Input name string.
 * @returns Greeting string.
 */
export function greet(name: string): string {
  return name;
}
`,
      'utf8',
    );

    const logSpy = vi.spyOn(console, 'log').mockImplementation(() => {});
    expect(verifyFrontendDocs(tmpDir)).toBe(0);
    // Also exercise default customSrcDir (verifying the real pulse-query-ng-web/src directory)
    expect(verifyFrontendDocs()).toBe(0);

    // Exercise runCliIfMain when mainModule === currentModule and when !==
    const exitSpy = vi.fn();
    const fakeModule = {};
    runCliIfMain(fakeModule, {}, exitSpy, tmpDir);
    expect(exitSpy).not.toHaveBeenCalled();
    runCliIfMain(fakeModule, fakeModule, exitSpy, tmpDir);
    expect(exitSpy).toHaveBeenCalledWith(0);

    const invalidFile = path.join(tmpDir, 'invalid.ts');
    fs.writeFileSync(
      invalidFile,
      `/** @docs */
export type BadId = string;
`,
      'utf8',
    );
    const errSpy = vi.spyOn(console, 'error').mockImplementation(() => {});
    expect(verifyFrontendDocs(tmpDir)).toBe(1);
    errSpy.mockRestore();
    logSpy.mockRestore();
    fs.rmSync(tmpDir, { recursive: true, force: true });
  });
});
