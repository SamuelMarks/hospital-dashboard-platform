import { Project, Node, SyntaxKind } from 'ts-morph';

const project = new Project({
  tsConfigFilePath: 'tsconfig.json',
});

const sourceFiles = project
  .getSourceFiles('src/**/*.ts')
  .filter((f) => !f.getFilePath().includes('.spec.ts') && !f.getFilePath().includes('api-client'));

function addDoc(node: any, message: string = 'Autogenerated doc') {
  if (node.getJsDocs && node.getJsDocs().length === 0) {
    node.addJsDoc(message);
  }
}

for (const sf of sourceFiles) {
  for (const cls of sf.getClasses()) {
    addDoc(cls);
    for (const prop of cls.getProperties()) addDoc(prop);
    for (const method of cls.getMethods()) addDoc(method);
    for (const ctor of cls.getConstructors()) addDoc(ctor);
    for (const get of cls.getGetAccessors()) addDoc(get);
    for (const set of cls.getSetAccessors()) addDoc(set);
  }
  for (const intf of sf.getInterfaces()) {
    addDoc(intf);
    for (const prop of intf.getProperties()) addDoc(prop);
    for (const method of intf.getMethods()) addDoc(method);
  }
  for (const type of sf.getTypeAliases()) {
    addDoc(type);
  }
  for (const fn of sf.getFunctions()) {
    addDoc(fn);
  }
  for (const v of sf.getVariableStatements()) {
    if (v.isExported()) {
      addDoc(v);
      for (const decl of v.getDeclarations()) {
         addDoc(decl);
      }
    }
  }
  for (const enumDec of sf.getEnums()) {
    addDoc(enumDec);
    for (const member of enumDec.getMembers()) addDoc(member);
  }
  
  sf.saveSync();
}
console.log('Docs added completely');
