/**
 * Enumerated clinical and administrative user roles within the hospital platform.
 *
 * @property wireValue Backend wire representation of the role.
 */
@Serializable
enum class ClinicalRole(val wireValue: String) {
    /** System administrator with full configuration and user management privileges. */
    @SerialName("ADMIN")
    ADMIN("ADMIN"),

    /** Attending or resident physician role. */
    @SerialName("PHYSICIAN")
    PHYSICIAN("PHYSICIAN"),

    /** Unit charge nurse managing bed flow and ward census. */
    @SerialName("CHARGE_NURSE")
    CHARGE_NURSE("CHARGE_NURSE"),

    /** Clinical operations data analyst role. */
    @SerialName("ANALYST")
    ANALYST("ANALYST");

    /**
     * Companion utilities for resolving [ClinicalRole] from wire strings.
     */
    companion object {
        /**
         * Resolves a [ClinicalRole] matching [raw] case-insensitively, defaulting to [ANALYST].
         *
         * @param raw Raw wire string.
         * @return Matching [ClinicalRole].
         */
        fun fromWire(raw: String): ClinicalRole =
            entries.firstOrNull { it.wireValue.equals(raw, ignoreCase = true) } ?: ANALYST
    }
}

