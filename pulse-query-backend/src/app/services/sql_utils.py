"""
SQL normalization and hashing helpers.

Provides a stable fingerprint for generated SQL so we can identify
identical queries across different LLMs for analytics and UI grouping.
"""

import hashlib
import re
from typing import Any

import sqlglot

_DEF_DIALECT = "duckdb"


def extract_sql_from_markdown(text: str) -> str:
  """
  Extracts SQL code from a markdown-formatted LLM response string.

  If a fenced code block (````sql ... ```` or ```` ... ````) is present,
  returns the inner trimmed SQL string; otherwise returns the trimmed text.

  Args:
      text (str): Raw markdown or plain SQL string generated by an LLM.

  Returns:
      str: Extracted SQL query string.
  """
  cleaned = (text or "").strip()
  pattern = r"```(?:sql)?(.*?)```"
  match = re.search(pattern, cleaned, re.DOTALL)
  if match:
    return match.group(1).strip()
  return cleaned


def interpolate_template_parameters(
  raw_sql: str,
  parameters_schema: dict[str, Any] | None = None,
  param_overrides: dict[str, Any] | None = None,
) -> str:
  """
  Substitutes `{{key}}` and `{{ key }}` handlebars placeholders in a SQL template
  using schema defaults and optional runtime parameter overrides.

  Args:
      raw_sql (str): SQL template containing `{{param}}` placeholders.
      parameters_schema (dict[str, Any] | None): JSON Schema describing template parameters.
      param_overrides (dict[str, Any] | None): Explicit parameter key-value overrides.

  Returns:
      str: Processed SQL query string with placeholders replaced.
  """
  processed_sql = raw_sql or ""
  resolved_values: dict[str, Any] = {}

  if isinstance(parameters_schema, dict):
    properties = parameters_schema.get("properties", {})
    if isinstance(properties, dict):
      for key, details in properties.items():
        if isinstance(details, dict) and details.get("default") is not None:
          resolved_values[key] = details.get("default")

  if isinstance(param_overrides, dict):
    for key, val in param_overrides.items():
      if val is not None:
        resolved_values[key] = val

  for key, val in resolved_values.items():
    str_val = str(val).replace("'", "''")
    processed_sql = processed_sql.replace(f"{{{{{key}}}}}", str_val)
    processed_sql = processed_sql.replace(f"{{{{ {key} }}}}", str_val)

  return processed_sql


def _skip_line_comment(sql: str, start_idx: int) -> tuple[str, int]:
  """
  Advances past a `--` SQL line comment starting at `start_idx`.

  Args:
      sql (str): Full SQL string.
      start_idx (int): Index of the first `-` in `--`.

  Returns:
      tuple[str, int]: Replacement whitespace/newline token and next index.
  """
  n = len(sql)
  i = start_idx + 2
  while i < n and sql[i] != "\n":
    i += 1
  token = "\n" if i < n and sql[i] == "\n" else " "
  return token, i + 1


def _skip_block_comment(sql: str, start_idx: int) -> tuple[str, int]:
  """
  Advances past a `/* ... */` SQL block comment starting at `start_idx`.

  Args:
      sql (str): Full SQL string.
      start_idx (int): Index of `/` in `/*`.

  Returns:
      tuple[str, int]: Single-space replacement token and next index.
  """
  n = len(sql)
  i = start_idx + 2
  while i < n - 1:
    if sql[i] == "*" and sql[i + 1] == "/":
      return " ", i + 2
    i += 1
  return " ", n


_QUOTE_CLOSERS: dict[str, str] = {"'": "'", '"': '"', "`": "`", "[": "]"}


def _strip_sql_comments(sql: str) -> str:
  """
  Remove SQL line and block comments while respecting quoted strings.

  Args:
      sql (str): Raw SQL string potentially containing comments.

  Returns:
      str: SQL string with comments stripped.
  """
  if not sql:
    return ""

  out: list[str] = []
  i = 0
  n = len(sql)
  closing_quote: str | None = None

  while i < n:
    ch = sql[i]
    nxt = sql[i + 1] if i + 1 < n else ""

    if closing_quote is None:
      if ch == "-" and nxt == "-":
        tok, i = _skip_line_comment(sql, i)
        out.append(tok)
        continue
      if ch == "/" and nxt == "*":
        tok, i = _skip_block_comment(sql, i)
        out.append(tok)
        continue
      closing_quote = _QUOTE_CLOSERS.get(ch)
      out.append(ch)
      i += 1
      continue

    if ch == closing_quote:
      if ch != "]" and nxt == closing_quote:
        out.append(ch + ch)
        i += 2
        continue
      closing_quote = None

    out.append(ch)
    i += 1

  return "".join(out)


def normalize_sql(sql: str, dialect: str = _DEF_DIALECT) -> str:
  """
  Normalize SQL into a canonical string for comparison.

  Tries to parse and re-emit SQL via sqlglot. Falls back to
  whitespace normalization if parsing fails.
  """
  cleaned = (sql or "").strip().rstrip(";")
  cleaned = _strip_sql_comments(cleaned)
  if not cleaned:
    return ""

  try:
    parsed = sqlglot.parse_one(cleaned, read=dialect)
    return str(parsed.sql(dialect=dialect, pretty=False))
  except Exception:
    # Fallback: collapse whitespace and lowercase for rough equivalence.
    return re.sub(r"\s+", " ", cleaned).strip().lower()


def sql_fingerprint(sql: str, dialect: str = _DEF_DIALECT) -> str | None:
  """
  Return a stable hash for the normalized SQL.
  """
  normalized = normalize_sql(sql, dialect=dialect)
  if not normalized:
    return None
  return hashlib.sha256(normalized.encode("utf-8")).hexdigest()
