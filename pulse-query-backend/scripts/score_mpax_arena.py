"""
MPAX Arena Scoring Metrics Module.

Provides evaluation routines for assessing LLM solutions against
mathematical ground truth generated by the MPAX optimization solver.
"""

from collections.abc import Mapping, Sequence
import json
import math
import os
import sys

sys.path.append(os.path.join(os.path.dirname(__file__), "../src"))

from app.schemas.json_types import JsonObject, JsonValue, SqlRow
from app.schemas.mpax_arena import MpaxArenaOutcome, MpaxSolverErrorPayload, MpaxSolverTruth


def extract_json_from_text(text: str) -> JsonObject:
  """
  Attempts to robustly extract JSON from LLM text output.

  Args:
      text (str): Raw string containing suspected JSON payload.

  Returns:
      JsonObject: Parsed JSON dictionary or empty dictionary on failure.
  """
  try:
    start = text.find("{")
    end = text.rfind("}")
    if start != -1 and end != -1:
      parsed: JsonObject = json.loads(text[start : end + 1])
      return parsed
  except Exception:
    pass
  return {}


def _extract_assignments_list(payload: MpaxArenaOutcome | Mapping[str, JsonValue]) -> list[JsonObject]:
  """
  Extracts a validated list of assignment dictionaries from an `MpaxArenaOutcome` or MPAX result mapping.

  Args:
      payload (MpaxArenaOutcome | Mapping[str, JsonValue]): Typed solver truth/error model or dictionary.

  Returns:
      list[JsonObject]: Filtered list of assignment dictionaries.
  """
  if isinstance(payload, MpaxSolverErrorPayload):
    return []
  if isinstance(payload, MpaxSolverTruth):
    return [a.model_dump(mode="json") for a in payload.assignments]
  raw = payload.get("assignments")
  return [item for item in raw if isinstance(item, dict)] if isinstance(raw, list) else []


def _to_float(val: JsonValue, default: float = 0.0) -> float:
  """
  Safely converts a `JsonValue` into a `float`.

  Args:
      val (JsonValue): Input JSON value.
      default (float): Fallback float when conversion fails.

  Returns:
      float: Converted float value.
  """
  try:
    return float(str(val)) if val is not None and not isinstance(val, bool) else default
  except (ValueError, TypeError):
    return default


def score_judge_mode(mpax_truth: MpaxArenaOutcome | Mapping[str, JsonValue], candidate_text: str) -> float:
  """
  Scores how well an LLM's logical routing matches the MPAX mathematical truth.

  Extracts assignments from text and computes Mean Absolute Error (MAE) against MPAX.

  Args:
      mpax_truth (MpaxArenaOutcome | Mapping[str, JsonValue]): Ground truth optimization result.
      candidate_text (str): Raw text generated by the competing model candidate.

  Returns:
      float: Allocation match score between 0.0 and 100.0.
  """
  truth_map: dict[str, float] = {}
  for a in _extract_assignments_list(mpax_truth):
    unit = str(a.get("Unit") or a.get("unit") or "Unknown")
    truth_map[unit] = truth_map.get(unit, 0.0) + _to_float(a.get("Patient_Count") or a.get("count"))

  llm_map = extract_json_from_text(candidate_text)
  if not llm_map:
    return 0.0

  error = 0.0
  all_units = set(truth_map.keys()).union(set(llm_map.keys()))
  for u in all_units:
    truth_val = float(truth_map.get(u, 0.0))
    llm_val = _to_float(llm_map.get(u, 0.0))
    error += abs(truth_val - llm_val)

  return max(0.0, 100.0 - (error * 10.0))


def score_constraints_mode(
  expected_metrics: Mapping[str, JsonValue],
  candidate_mpax_result: MpaxArenaOutcome | Mapping[str, JsonValue],
) -> float:
  """
  Scores how well the LLM-generated constraints performed when fed into MPAX.

  Args:
      expected_metrics (Mapping[str, JsonValue]): Benchmark scenario target metrics including 'expected_overflow'.
      candidate_mpax_result (MpaxArenaOutcome | Mapping[str, JsonValue]): MPAX execution result model or dictionary.

  Returns:
      float: Constraint adherence score between 0.0 and 100.0.
  """
  if isinstance(candidate_mpax_result, MpaxSolverErrorPayload) or candidate_mpax_result["status"] == "error":
    return 0.0

  assignments = _extract_assignments_list(candidate_mpax_result)
  overflow = sum(
    _to_float(a.get("Patient_Count") or a.get("count"))
    for a in assignments
    if str(a.get("Unit") or a.get("unit")).lower() == "overflow"
  )

  expected_overflow = _to_float(expected_metrics.get("expected_overflow", 0.0))
  error = abs(overflow - expected_overflow)
  return max(0.0, 100.0 - (error * 20.0))


def _parse_sql_row_allocation(row: Mapping[str, JsonValue] | SqlRow) -> tuple[str | None, float | None]:
  """
  Extracts `(unit_name, patient_count)` from a candidate SQL result row dictionary.

  Args:
      row (Mapping[str, JsonValue] | SqlRow): Candidate SQL row dictionary.

  Returns:
      tuple[str | None, float | None]: Extracted unit name and count, or `(None, None)`.
  """
  unit_name: str | None = None
  count_val: float | None = None

  for key, val in row.items():
    k_lower = key.lower()
    if k_lower in ("unit", "assigned_unit", "unit_category", "department", "unit_name", "target_unit"):
      unit_name = str(val)
    elif k_lower in ("patient_count", "count", "patients", "assigned", "total", "volume", "census"):
      try:
        count_val = float(str(val)) if val is not None and not isinstance(val, bool) else 0.0
      except (ValueError, TypeError):
        count_val = 0.0
  return unit_name, count_val


def _parse_sql_unit_allocations(raw_rows: Sequence[JsonValue | SqlRow]) -> dict[str, float]:
  """
  Aggregates patient counts per unit across all candidate SQL result rows.

  Args:
      raw_rows (Sequence[JsonValue | SqlRow]): Sequence of SQL row dictionaries.

  Returns:
      dict[str, float]: Mapping of unit name to total allocated patients.
  """
  sql_map: dict[str, float] = {}
  for row in raw_rows:
    if not isinstance(row, Mapping):
      continue
    unit_name, count_val = _parse_sql_row_allocation(row)
    if unit_name is not None and count_val is not None:
      sql_map[unit_name] = sql_map.get(unit_name, 0.0) + count_val
  return sql_map


def score_sql_vs_mpax_mode(
  mpax_truth: MpaxArenaOutcome | Mapping[str, JsonValue],
  candidate_sql_result: Mapping[str, JsonValue],
) -> float:
  """
  Compares the patient allocation distribution achieved by candidate SQL vs MPAX Global Optimization.

  Parses candidate SQL execution rows, matches hospital unit allocations against
  ground truth assignments, calculates unit-by-unit Mean Absolute Error (MAE),
  and returns a penalized accuracy score between 0.0 and 100.0.

  Args:
      mpax_truth (MpaxArenaOutcome | Mapping[str, JsonValue]): Ground truth model or dictionary containing 'assignments'.
      candidate_sql_result (Mapping[str, JsonValue]): Execution result dictionary containing 'data' or 'error'.

  Returns:
      float: Allocation accuracy score between 0.0 and 100.0.
  """
  if candidate_sql_result.get("error"):
    return 0.0

  raw_rows = candidate_sql_result.get("data")
  if raw_rows is None and "assignments" in candidate_sql_result:
    raw_rows = candidate_sql_result.get("assignments")

  if not isinstance(raw_rows, list) or not raw_rows:
    return 0.0

  truth_map: dict[str, float] = {}
  for a in _extract_assignments_list(mpax_truth):
    unit = str(a.get("Unit") or a.get("unit") or "Unknown")
    count = _to_float(a.get("Patient_Count") or a.get("count"))
    truth_map[unit] = truth_map.get(unit, 0.0) + count

  sql_map = _parse_sql_unit_allocations(raw_rows)
  if not sql_map:
    return 0.0

  all_units = set(truth_map.keys()).union(set(sql_map.keys()))
  total_error = 0.0
  squared_error = 0.0

  for u in all_units:
    diff = abs(truth_map.get(u, 0.0) - sql_map.get(u, 0.0))
    total_error += diff
    squared_error += diff**2

  rmse = math.sqrt(squared_error / max(len(all_units), 1))
  total_demand = sum(truth_map.values())

  if total_demand <= 0.0:
    return 100.0 if total_error == 0.0 else 0.0

  relative_error = total_error / (2.0 * total_demand)
  mae_component = max(0.0, 1.0 - relative_error) * 80.0
  rmse_penalty = min(20.0, rmse * 2.0)

  final_score = max(0.0, mae_component + (20.0 - rmse_penalty))
  return round(final_score, 2)


def score_critic_mode(candidate_score: int) -> float:
  """
  Converts integer candidate score into floating-point format for Arena aggregation.

  Args:
      candidate_score (int): Raw integer score evaluated by critic mode.

  Returns:
      float: Floating-point converted score.
  """
  return float(candidate_score)
